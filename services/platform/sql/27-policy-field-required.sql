-- 27-policy-field-required.sql —— 字段的「必填」按**角色**（并可按状态）配。
--
-- ── 为什么要有这一列 ────────────────────────────────────────────────────
--
-- `business-schema` 的 `Field.required` 是**模型层**的：这个字段在业务上必须有值。
-- 而氚云的[字段权限](https://help.h3yun.com/236514731/)把「必填」放在**权限**那一层，
-- 它配的是「**这个角色**在这一步必须把它填上」——
--
--     「新增数据权限：新增数据时，默认全员用此权限」
--     「当表单开启流程时，可在 流程设计 > 节点中设置操作权限」
--
-- 两者不冲突，是两道叠加的闸：模型层是**下限**（对所有人成立），
-- 权限层可以**再收窄**（「跟进状态」全局可以不填，但主管必须填）。
--
-- ── 语义 ────────────────────────────────────────────────────────────────
--
--   field_required = true  → 该角色在**创建**记录时，这个字段必须带值；
--                            在**修改**时若写这个字段，不能写成空。
--   field_required = false → 没有额外的必填要求（模型层的 `required` 照旧成立）。
--
-- 与 `state_code` 相乘：策略写了状态，则「必填」只在那个状态下成立
-- （那就是氚云「节点上必填」的对应物）。不写状态 = 所有状态都必填。
--
-- ── 为什么不能把它并进 `field_visibility` ───────────────────────────────
--
-- 「可见性」和「必填」是**两个正交的轴**。挤进同一个枚举会丢掉组合：
--   · 「可见可写但不必填」与「可见可写且必填」→ 枚举勉强能分；
--   · 「**只读**且必填」→ 表达不了。而它是合法且常见的：值由别人或流程填，
--     但在你这一步它必须已经存在（审批节点上「确认金额已填」就是这个意思）。
-- 所以另立一列，不是给可见性加一个档位。

ALTER TABLE policies ADD COLUMN IF NOT EXISTS field_required boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN policies.field_required IS
  '该角色在这一档上是否必须给这个字段一个值；与 state_code 相乘可表达「某个状态下必填」';
