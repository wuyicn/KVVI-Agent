-- 草案**要发布的内容**：提交时存下来，发布时按它执行。
--
-- ── 它补的是什么 ────────────────────────────────────────────────────────
--
-- 第一版的 `publishDraft` 要求**发布方**把契约内容再传一遍，平台拿它重新编译。
-- 于是「审批」与「发布」之间有一个缺口：审批人批的是差异报告，
-- 而发布时用的是**另一次**编译的结果。两次编译只要有一处不同
-- （契约改了一行、编译逻辑改了一版），发出去的东西就和批过的东西不是同一份 ——
-- 而 `change_digest` 只能证明「变更对象没变」，证明不了「发的内容是那一份」。
--
-- 现在提交时把编译结果存进草案，发布**只认草案里的那一份**。
-- 审批人不需要、也无法重新提供内容 —— 他能做的只有批准或驳回。
--
-- ── 为什么不放 `change_digest` 就够 ──────────────────────────────────────
--
-- 摘要是**单向**的：它证明两样东西相同，但不提供那两样东西。
-- 发布要用的是内容本身（策略行、系统代号、契约内容），
-- 所以存的是内容，摘要继续留在 `change_digest` 那一列上守它自己的那一问。
ALTER TABLE publish_drafts
  ADD COLUMN IF NOT EXISTS payload jsonb NOT NULL DEFAULT '{}'::jsonb;
